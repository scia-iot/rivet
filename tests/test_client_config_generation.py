from pathlib import Path
from unittest.mock import patch

import pytest

from sciaiot.rivet.services.client_config import (
    ClientConfigGenerationError,
    normalize_remote_host,
    render_client_config,
    replace_client_config,
)


def server_config(**updates: object) -> dict[str, object]:
    config: dict[str, object] = {
        "port": "1194",
        "proto": "udp",
        "dev": "tun",
        "persist_key": True,
        "persist_tun": True,
        "data_ciphers_fallback": "AES-256-CBC",
        "verb": "3",
        "explicit_exit_notify": "1",
    }
    config.update(updates)
    return config


@pytest.mark.parametrize(
    "value",
    [
        "",
        "vpn host.example",
        "-vpn.example",
        "vpn..example",
        "256.256.256.256",
        "ff02::1",
        "fe80::1%eth0",
        "fe80::1",
        "::1",
        "127.0.0.1",
        "169.254.1.2",
        "localhost",
        "a" * 254,
    ],
)
def test_remote_host_rejects_unsafe_values(value: str) -> None:
    with pytest.raises(ValueError):
        normalize_remote_host(value)


@pytest.mark.parametrize(
    ("value", "expected"),
    [
        ("VPN.Example.Test.", "vpn.example.test"),
        ("192.0.2.10", "192.0.2.10"),
        ("2001:0db8::1", "2001:db8::1"),
    ],
)
def test_remote_host_normalizes_safe_values(value: str, expected: str) -> None:
    assert normalize_remote_host(value) == expected


